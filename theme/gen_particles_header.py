"""Embeds the built-in particle textures in a C++ header.

Usage: python gen_particles_header.py <THEME/particles> <shellui/include/zt_particle_textures.hpp>

The textures (THEME/particles/*.png) are AniketosHEN's
(git.etawen.dev/Alex0/AniketosHEN, GPL-3.0, source/shellui/assets/particles/builtin),
the ones its 23 built-in particle styles use, plus ZhiThemes' own white
controller buttons btn_*.png (make_button_icons.py). zt_particles_install()
(zt_storage.cpp) writes them to /data/ZhiThemes/Assets/particles/ at start;
theme.js (StyledParticles) shows them from there.
"""
import os
import re
import sys

src, out = sys.argv[1], sys.argv[2]
names = sorted(f[:-4] for f in os.listdir(src) if f.endswith('.png'))
parts = ['/* Generated by THEME/gen_particles_header.py from THEME/particles - do not edit.\n'
         '   Textures from AniketosHEN (GPL-3.0); btn_* are ZhiThemes own. */\n#pragma once\n\n'
         'struct ZtParticleTexture {\n  const char *name;\n  const unsigned char *data;\n  unsigned size;\n};\n\n']
total = 0
for n in names:
    if not re.fullmatch(r'[a-z0-9_]+', n):
        sys.exit('bad texture name ' + n)
    data = open(os.path.join(src, n + '.png'), 'rb').read()
    total += len(data)
    lines = ['  ' + ','.join(str(b) for b in data[i:i + 32]) + ',' for i in range(0, len(data), 32)]
    parts.append('static const unsigned char kZtPt_' + n + '[] = {\n' + '\n'.join(lines) + '\n};\n')
parts.append('\nstatic const ZtParticleTexture kZtParticleTextures[] = {\n' +
             '\n'.join('  {"%s", kZtPt_%s, sizeof(kZtPt_%s)},' % (n, n, n) for n in names) + '\n};\n')
open(out, 'w', encoding='utf-8', newline='\n').write(''.join(parts))
print('ok', len(names), 'textures', total, 'bytes')

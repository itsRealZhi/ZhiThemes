"""Embeds a text file in a C++ header (byte array).

Usage: python gen_theme_header.py <input> <output.hpp> [symbol]
  - THEME/theme_factory.js -> shellui/include/theme_default_js.hpp (kThemeDefaultJs)
  - THEME/editor.html      -> shellui/include/theme_web_page.hpp   (kThemeWebPage)

It used to be a raw string; that went past the compiler's string literal size
limit (-Woverlength-strings with -pedantic), so now it is a 0-terminated byte
array, used the same way (const char[]).
"""
import os
import sys

data = open(sys.argv[1], 'rb').read()
symbol = sys.argv[3] if len(sys.argv) > 3 else 'kThemeDefaultJs'
name = os.path.basename(sys.argv[1])

lines = []
for i in range(0, len(data), 24):
    # char is signed: bytes above 127 are written as negatives (no narrowing)
    lines.append('  ' + ', '.join(str(b if b < 128 else b - 256) for b in data[i:i + 24]) + ',')
header = (
    '/* Generated by THEME/gen_theme_header.py from THEME/' + name + ' - do not edit. */\n'
    '#pragma once\n\n'
    'static const char ' + symbol + '[] = {\n' + '\n'.join(lines) + '\n  0};\n'
)
open(sys.argv[2], 'w', encoding='utf-8', newline='\n').write(header)
print('ok', name, len(data), 'bytes')
